// Builds the ChatGPT half of the extension: src/chatgpt/** → chatgpt/** (committed, so the repo
// root loads unpacked without a build step). The manifest, popup and Claude half are plain files.
import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(fileURLToPath(new URL('../..', import.meta.url)));
const src = path.join(root, 'src', 'chatgpt');
const out = path.join(root, 'chatgpt');
const { version } = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
const common = ['core/config.js', 'core/safety.js', 'core/protocol.js'];
const bundles = {
  'main-world.js': [...common, 'core/endpoints.js', 'core/auth.js', 'core/transfer.js', 'core/files.js', 'core/transcript.js', 'core/controller.js', 'main-world.js'],
  'content.js': [...common, 'content.js'],
  'service-worker.js': [...common, 'service-worker.js'],
  'popup/popup.js': [...common, 'popup/popup.js'],
  // Full archive: the page bundle runs in a chatgpt.com tab's MAIN world; the archive bundle is an
  // extension page that only ever sees JSON and file bytes handed back by it.
  'archive-page.js': [...common, 'core/endpoints.js', 'core/transfer.js', 'core/files.js', 'archive/page-api.js'],
  'archive/archive.js': [...common, 'core/transcript.js', 'archive/render.js', 'archive/archive.js'],
};
await mkdir(path.join(out, 'popup'), { recursive: true });
await mkdir(path.join(out, 'archive'), { recursive: true });
// Source modules are named, closed factories. Concatenating them inside a single
// IIFE keeps MAIN secrets private and needs no package installation or remote bundler.
for (const [target, sources] of Object.entries(bundles)) {
  const bodies = await Promise.all(sources.map(async source => `// Source: src/chatgpt/${source}\n${await readFile(path.join(src, source), 'utf8')}`));
  await writeFile(path.join(out, target), `// ChatGPT + Claude Backup v${version} (ChatGPT part) — generated by npm run build\n(() => {\n'use strict';\n${bodies.join('\n\n')}\n})();\n`);
}
for (const file of ['popup.html', 'popup.css']) await copyFile(path.join(src, 'popup', file), path.join(out, 'popup', file));
for (const file of ['archive.html', 'timer.js']) await copyFile(path.join(src, 'archive', file), path.join(out, 'archive', file));
console.log('Built chatgpt/ — load the repository folder unpacked in Chrome.');
